"""
Cargo project builder for the experimental Python-to-Rust conversion system.

Creates a valid Cargo project structure under ``rust_experiment/`` and invokes
``cargo check`` / ``cargo build`` to compile the generated Rust code.
"""

from __future__ import annotations

import shutil
import subprocess
import textwrap
from pathlib import Path


# Cargo binary – prefer the full path on Windows if not on PATH
CARGO_BIN = shutil.which("cargo") or str(
    Path.home() / ".cargo" / "bin" / "cargo.exe"
)


class CargoProjectBuilder:
    """
    Manages the ``rust_experiment/`` Cargo project lifecycle.

    Responsibilities:
    * Create/overwrite ``Cargo.toml`` and ``src/`` layout.
    * Write generated ``.rs`` files.
    * Generate a ``main.rs`` entry-point that exercises converted modules.
    * Run ``cargo check`` and ``cargo build``.
    """

    def __init__(self, project_dir: Path | str) -> None:
        self.project_dir = Path(project_dir).resolve()
        self.src_dir = self.project_dir / "src"

    # ------------------------------------------------------------------
    # Cargo.toml
    # ------------------------------------------------------------------

    def write_cargo_toml(self, name: str = "btc_straddle_experiment") -> Path:
        """
        Write a minimal Cargo.toml for the generated project.
        """
        cargo_toml = self.project_dir / "Cargo.toml"
        content = textwrap.dedent(f"""\
            [package]
            name = "{name}"
            version = "0.1.0"
            edition = "2021"
            description = "Auto-generated experimental Rust port of selected Python modules"

            # No external dependencies for the initial experiment.
            [dependencies]
        """)
        self.project_dir.mkdir(parents=True, exist_ok=True)
        cargo_toml.write_text(content, encoding="utf-8")
        return cargo_toml

    # ------------------------------------------------------------------
    # Generated Rust source files
    # ------------------------------------------------------------------

    def write_module(self, module_name: str, rust_source: str) -> Path:
        """Write a generated ``.rs`` file under ``src/``."""
        self.src_dir.mkdir(parents=True, exist_ok=True)
        rs_path = self.src_dir / f"{module_name}.rs"
        rs_path.write_text(rust_source, encoding="utf-8")
        return rs_path

    def write_main(self, module_names: list[str]) -> Path:
        """
        Generate ``src/main.rs`` that declares all converted modules and runs
        a simple demonstration.
        """
        self.src_dir.mkdir(parents=True, exist_ok=True)
        lines: list[str] = [
            "// Auto-generated entry point for the experimental Python → Rust project.",
            "// DO NOT edit manually – this file is regenerated by the converter.",
            "",
        ]

        # Declare modules
        for name in module_names:
            lines.append(f"mod {name};")
        lines.append("")

        # Main function
        lines.append("fn main() {")
        lines.append('    println!("========================================");')
        lines.append('    println!("  BTC Straddle – Experimental Rust Port");')
        lines.append('    println!("========================================");')
        lines.append('    println!();')
        lines.append("")

        for name in module_names:
            lines.append(f'    println!("--- Module: {name} ---");')
            lines.append(f"    {name}::demo();")
            lines.append('    println!();')

        lines.append('    println!("All modules executed successfully.");')
        lines.append("}")
        lines.append("")

        main_rs = self.src_dir / "main.rs"
        main_rs.write_text("\n".join(lines), encoding="utf-8")
        return main_rs

    # ------------------------------------------------------------------
    # Build commands
    # ------------------------------------------------------------------

    def cargo_check(self) -> subprocess.CompletedProcess[str]:
        """Run ``cargo check`` inside the project directory."""
        return subprocess.run(
            [CARGO_BIN, "check"],
            cwd=str(self.project_dir),
            capture_output=True,
            text=True,
        )

    def cargo_build(self, release: bool = False) -> subprocess.CompletedProcess[str]:
        """Run ``cargo build`` inside the project directory."""
        cmd = [CARGO_BIN, "build"]
        if release:
            cmd.append("--release")
        return subprocess.run(
            cmd,
            cwd=str(self.project_dir),
            capture_output=True,
            text=True,
        )

    def cargo_run(self) -> subprocess.CompletedProcess[str]:
        """Run ``cargo run`` inside the project directory."""
        return subprocess.run(
            [CARGO_BIN, "run"],
            cwd=str(self.project_dir),
            capture_output=True,
            text=True,
        )

    def get_executable_path(self, release: bool = False) -> Path:
        """Return the expected path of the compiled binary."""
        profile = "release" if release else "debug"
        name = self.project_dir.name
        # On Windows the binary has a .exe extension
        import sys

        ext = ".exe" if sys.platform == "win32" else ""
        return self.project_dir / "target" / profile / f"{name}{ext}"

    def clean(self) -> None:
        """Remove the ``target/`` directory (``cargo clean``)."""
        target_dir = self.project_dir / "target"
        if target_dir.exists():
            shutil.rmtree(target_dir)
